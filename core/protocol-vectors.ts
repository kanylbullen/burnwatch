/**
 * Builds `protocol/vectors.json` from the reference implementation.
 *
 *   bun run protocol:vectors
 *
 * Every input is fixed, so the output only changes when the protocol does. The
 * test in `protocol.test.ts` regenerates it and fails if the committed file
 * differs, so the file and the code cannot drift apart.
 */

import * as p from "./protocol";

const label = (s: string) => new TextEncoder().encode(s);
/** A fixed 32-byte value per name, so each input is reproducible by hand. */
const fixed = (name: string) => p.sha256(label(`burnwatch vector ${name}`));

export function buildVectors() {
  // RFC 7748 §6.1: anyone can check these against the RFC itself, which pins
  // the X25519 implementation before anything of ours is involved.
  const alice = p.unhex(
    "77076d0a7318a57d3c16c17251b26645df4c2f87ebc0992ab177fba51db92c2a",
  );
  const bob = p.unhex(
    "5dab087e624a8a4b79e17f8b83800ee66f3bb1292618b6fd1c2f8b27ff88e0eb",
  );

  // --- channel ---
  const secret = fixed("channel secret");
  const writeToken = fixed("write token");
  const ch = p.deriveChannel(secret);

  // --- state ---
  const stateNonce = fixed("state nonce").subarray(0, 12);
  const stateBody: p.StatePlaintext = {
    v: 1,
    issued_at: 1_786_000_000,
    state: { windows: { seven_day: { pct: 42, verdict: "runs_out" } } },
  };
  const stateJson = JSON.stringify(stateBody);
  const stateEnvelope = p.sealState(ch, stateNonce, stateBody);
  const tampered = Uint8Array.from(stateEnvelope);
  tampered[20]! ^= 0x01;
  const wrongVersion = Uint8Array.from(stateEnvelope);
  wrongVersion[0] = 0x02;

  // --- pairing ---
  const codeBytes = fixed("code").subarray(0, 5);
  const code = p.codeFromBytes(codeBytes);
  const dsk = alice;
  const hsk = bob;
  const dpk = p.publicKeyOf(dsk);
  const hpk = p.publicKeyOf(hsk);
  const nD = fixed("device nonce");
  const nH = fixed("hub nonce");
  const commit = p.pairCommit(dpk, nD);
  const transcript = p.transcriptHash({ code, commit, hpk, nH, dpk, nD });
  const keyD = p.pairKey(dsk, hpk, transcript);
  const keyH = p.pairKey(hsk, dpk, transcript);
  if (p.hex(keyD) !== p.hex(keyH)) throw new Error("pair keys disagree");
  const sealNonce = fixed("seal nonce").subarray(0, 12);
  const sealBody: p.SealPlaintext = {
    v: 1,
    relay: "https://relay.example",
    secret: p.b64u(secret),
  };
  const sealEnvelope = p.sealPairing(keyH, sealNonce, transcript, sealBody);

  return {
    description:
      "Test vectors for protocol/README.md. Binary values are lowercase hex unless the field name ends in _b64u. Generated by core/protocol-vectors.ts; do not edit by hand.",
    version: 1,
    x25519: {
      rfc7748: {
        alice_sk: p.hex(alice),
        alice_pk: p.hex(p.publicKeyOf(alice)),
        bob_sk: p.hex(bob),
        bob_pk: p.hex(p.publicKeyOf(bob)),
        shared: p.hex(p.x25519(alice, p.publicKeyOf(bob))),
      },
      // Must be rejected: the all-zero point yields an all-zero shared secret.
      low_order_pk: p.hex(new Uint8Array(32)),
    },
    channel: {
      secret: p.hex(secret),
      channel_id: p.hex(ch.channelId),
      channel_id_b64u: p.b64u(ch.channelId),
      read_token: p.hex(ch.readToken),
      read_token_b64u: p.b64u(ch.readToken),
      read_hash_b64u: p.tokenHash(ch.readToken),
      state_key: p.hex(ch.stateKey),
      write_token: p.hex(writeToken),
      write_token_b64u: p.b64u(writeToken),
      write_hash_b64u: p.tokenHash(writeToken),
    },
    state: {
      nonce: p.hex(stateNonce),
      plaintext_utf8: stateJson,
      aad: p.hex(p.concat(label("burnwatch/v1 state "), ch.channelId)),
      envelope: p.hex(stateEnvelope),
      // Each of these must fail to open.
      reject: {
        tampered: p.hex(tampered),
        wrong_version: p.hex(wrongVersion),
        truncated: p.hex(stateEnvelope.subarray(0, 28)),
      },
    },
    code: {
      bytes: p.hex(codeBytes),
      code,
      display: p.formatCode(code),
      normalize: [
        [p.formatCode(code).toLowerCase(), code],
        [` ${code.slice(0, 4)} ${code.slice(4)} `, code],
        ["0IL0-ol1i", "0110" + "0111"],
        ["ABCD-EFGU", null],
        ["ABC-DEF", null],
        ["", null],
      ],
    },
    pairing: {
      code,
      device_sk: p.hex(dsk),
      device_pk: p.hex(dpk),
      device_nonce: p.hex(nD),
      commit: p.hex(commit),
      hub_sk: p.hex(hsk),
      hub_pk: p.hex(hpk),
      hub_nonce: p.hex(nH),
      transcript: p.hex(transcript),
      sas: p.sas(transcript),
      sas_display: p.formatSas(p.sas(transcript)),
      pair_key: p.hex(keyH),
      seal_nonce: p.hex(sealNonce),
      seal_plaintext_utf8: JSON.stringify(sealBody),
      seal_aad: p.hex(p.concat(label("burnwatch/v1 pair-seal "), transcript)),
      seal: p.hex(sealEnvelope),
    },
  };
}

if (import.meta.main) {
  process.stdout.write(JSON.stringify(buildVectors(), null, 2) + "\n");
}
